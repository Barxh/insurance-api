CREATE TABLE insurance_product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

ALTER TABLE insurance_product
    ADD CONSTRAINT uk_insurance_product_name UNIQUE (name);


CREATE TABLE insurance_package (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    price NUMERIC(12, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'RSD',
    active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_insurance_package_product
        FOREIGN KEY (product_id)
        REFERENCES insurance_product(id),

    CONSTRAINT ck_insurance_package_price
        CHECK (price >= 0)
);

ALTER TABLE insurance_package
    ADD CONSTRAINT uk_insurance_package_product_name UNIQUE (product_id, name);

CREATE INDEX idx_insurance_package_product_id
    ON insurance_package (product_id);


CREATE TABLE insurance_coverage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    limit_amount NUMERIC(12, 2),
    limit_currency VARCHAR(3),

    CONSTRAINT fk_insurance_coverage_package
        FOREIGN KEY (package_id)
        REFERENCES insurance_package(id)
        ON DELETE CASCADE,

    CONSTRAINT ck_insurance_coverage_limit
        CHECK (limit_amount >= 0)
);

ALTER TABLE insurance_coverage
    ADD CONSTRAINT uk_insurance_coverage_package_name UNIQUE (package_id, name);

CREATE INDEX idx_insurance_coverage_package_id
    ON insurance_coverage (package_id);


CREATE TABLE insurance_addon (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    price NUMERIC(12, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'RSD',
    active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT ck_insurance_addon_price
        CHECK (price >= 0)
);

ALTER TABLE insurance_addon
    ADD CONSTRAINT uk_insurance_addon_name UNIQUE (name);


CREATE TABLE product_addon (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    addon_id BIGINT NOT NULL,

    CONSTRAINT fk_product_addon_product
        FOREIGN KEY (product_id)
        REFERENCES insurance_product(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_product_addon_addon
        FOREIGN KEY (addon_id)
        REFERENCES insurance_addon(id)
        ON DELETE CASCADE,

    CONSTRAINT uk_product_addon
        UNIQUE (product_id, addon_id)
);

CREATE INDEX idx_product_addon_product_id
    ON product_addon (product_id);

CREATE INDEX idx_product_addon_addon_id
    ON product_addon (addon_id);