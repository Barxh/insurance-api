

CREATE TABLE policy (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    package_id BIGINT NOT NULL,

    package_name VARCHAR(100) NOT NULL,
    package_price NUMERIC(12, 2) NOT NULL,
    package_currency VARCHAR(3) NOT NULL,

    total_price NUMERIC(12, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,

    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_policy_user
        FOREIGN KEY (user_id)
        REFERENCES _user(id),

    CONSTRAINT fk_policy_product
        FOREIGN KEY (product_id)
        REFERENCES insurance_product(id),

    CONSTRAINT fk_policy_package
        FOREIGN KEY (package_id)
        REFERENCES insurance_package(id),

    CONSTRAINT ck_policy_package_price
        CHECK (package_price >= 0),

    CONSTRAINT ck_policy_total_price
        CHECK (total_price >= 0),

    CONSTRAINT ck_policy_dates
        CHECK (end_date >= start_date),

    CONSTRAINT ck_policy_status
        CHECK (status IN ('ACTIVE', 'EXPIRED', 'CANCELLED'))
);

CREATE INDEX idx_policy_user_id
    ON policy (user_id);

CREATE INDEX idx_policy_product_id
    ON policy (product_id);

CREATE INDEX idx_policy_package_id
    ON policy (package_id);

CREATE INDEX idx_policy_status
    ON policy (status);


CREATE TABLE policy_addon (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id BIGINT NOT NULL,
    addon_id BIGINT NOT NULL,

    addon_name VARCHAR(100) NOT NULL,
    addon_price NUMERIC(12, 2) NOT NULL,
    addon_currency VARCHAR(3) NOT NULL,

    CONSTRAINT fk_policy_addon_policy
        FOREIGN KEY (policy_id)
        REFERENCES policy(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_policy_addon_addon
        FOREIGN KEY (addon_id)
        REFERENCES insurance_addon(id),

    CONSTRAINT ck_policy_addon_price
        CHECK (addon_price >= 0),

    CONSTRAINT uk_policy_addon
        UNIQUE (policy_id, addon_id)
);

CREATE INDEX idx_policy_addon_policy_id
    ON policy_addon (policy_id);


CREATE TABLE policy_coverage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id BIGINT NOT NULL,
    coverage_id BIGINT NOT NULL,

    coverage_name VARCHAR(100) NOT NULL,
    limit_amount NUMERIC(12, 2),
    limit_currency VARCHAR(3),

    CONSTRAINT fk_policy_coverage_policy
        FOREIGN KEY (policy_id)
        REFERENCES policy(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_policy_coverage_coverage
        FOREIGN KEY (coverage_id)
        REFERENCES insurance_coverage(id),

    CONSTRAINT ck_policy_coverage_limit
        CHECK (limit_amount >= 0),

    CONSTRAINT uk_policy_coverage
        UNIQUE (policy_id, coverage_id)
);

CREATE INDEX idx_policy_coverage_policy_id
    ON policy_coverage (policy_id);