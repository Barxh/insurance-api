ALTER TABLE insurance_product ADD COLUMN insurance_type VARCHAR(30);

CREATE TABLE travel_pricing_rate (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id BIGINT NOT NULL REFERENCES insurance_package(id) ON DELETE CASCADE,
    region VARCHAR(20) NOT NULL,
    age_group VARCHAR(20) NOT NULL,
    daily_rate NUMERIC(12,2) NOT NULL CHECK (daily_rate >= 0),
    currency VARCHAR(3) NOT NULL,
    CONSTRAINT uk_travel_rate_package_region_age UNIQUE(package_id, region, age_group)
);

CREATE TABLE property_pricing_rate (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id BIGINT NOT NULL UNIQUE REFERENCES insurance_package(id) ON DELETE CASCADE,
    price_per_square_meter NUMERIC(12,2) NOT NULL CHECK (price_per_square_meter >= 0),
    currency VARCHAR(3) NOT NULL,
    CONSTRAINT uk_property_rate_package UNIQUE(package_id)
);

CREATE TABLE roadside_pricing_rate (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id BIGINT NOT NULL REFERENCES insurance_package(id) ON DELETE CASCADE,
    vehicle_type VARCHAR(20) NOT NULL,
    annual_price NUMERIC(12,2) NOT NULL CHECK (annual_price >= 0),
    currency VARCHAR(3) NOT NULL,
    CONSTRAINT uk_roadside_rate_package_vehicle UNIQUE(package_id, vehicle_type)
);

