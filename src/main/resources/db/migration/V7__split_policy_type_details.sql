CREATE TABLE travel_policy_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id BIGINT NOT NULL UNIQUE
        REFERENCES policy(id) ON DELETE CASCADE,
    region VARCHAR(20) NOT NULL
);

INSERT INTO travel_policy_details (policy_id, region)
SELECT id, travel_region
FROM policy
WHERE travel_region IS NOT NULL;

CREATE TABLE property_policy_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id BIGINT NOT NULL UNIQUE
        REFERENCES policy(id) ON DELETE CASCADE,
    area_sqm NUMERIC(10,2) NOT NULL CHECK (area_sqm >= 20),
    rate_per_square_meter NUMERIC(12,2) NOT NULL
        CHECK (rate_per_square_meter >= 0)
);

INSERT INTO property_policy_details (
    policy_id,
    area_sqm,
    rate_per_square_meter
)
SELECT id, property_area_sqm, property_rate_per_square_meter
FROM policy
WHERE property_area_sqm IS NOT NULL
  AND property_rate_per_square_meter IS NOT NULL;

CREATE TABLE roadside_policy_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id BIGINT NOT NULL UNIQUE
        REFERENCES policy(id) ON DELETE CASCADE,
    vehicle_type VARCHAR(20) NOT NULL,
    annual_price NUMERIC(12,2) NOT NULL CHECK (annual_price >= 0)
);

INSERT INTO roadside_policy_details (
    policy_id,
    vehicle_type,
    annual_price
)
SELECT id, vehicle_type, vehicle_annual_price
FROM policy
WHERE vehicle_type IS NOT NULL
  AND vehicle_annual_price IS NOT NULL;

ALTER TABLE policy_insured_person
    ADD COLUMN travel_details_id BIGINT;

UPDATE policy_insured_person insured
SET travel_details_id = details.id
FROM travel_policy_details details
WHERE details.policy_id = insured.policy_id;

ALTER TABLE policy_insured_person
    ALTER COLUMN travel_details_id SET NOT NULL,
    ADD CONSTRAINT fk_insured_person_travel_details
        FOREIGN KEY (travel_details_id)
        REFERENCES travel_policy_details(id)
        ON DELETE CASCADE;

ALTER TABLE policy_insured_person
    DROP CONSTRAINT uk_policy_insured_jmbg,
    DROP COLUMN policy_id,
    ADD CONSTRAINT uk_policy_insured_jmbg
        UNIQUE (travel_details_id, jmbg);

ALTER TABLE policy
    DROP COLUMN travel_region,
    DROP COLUMN property_area_sqm,
    DROP COLUMN property_rate_per_square_meter,
    DROP COLUMN vehicle_type,
    DROP COLUMN vehicle_annual_price;
