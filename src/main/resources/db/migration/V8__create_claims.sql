CREATE TABLE insurance_claim (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id BIGINT NOT NULL,
    submitted_by_id BIGINT NOT NULL,
    incident_date DATE NOT NULL,
    description VARCHAR(2000) NOT NULL,
    requested_amount NUMERIC(12, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_by_id BIGINT,
    reviewed_at TIMESTAMP,
    decision_note VARCHAR(1000),

    CONSTRAINT fk_claim_policy
        FOREIGN KEY (policy_id)
        REFERENCES policy(id),

    CONSTRAINT fk_claim_submitted_by
        FOREIGN KEY (submitted_by_id)
        REFERENCES _user(id),

    CONSTRAINT fk_claim_reviewed_by
        FOREIGN KEY (reviewed_by_id)
        REFERENCES _user(id),

    CONSTRAINT ck_claim_requested_amount
        CHECK (requested_amount > 0),

    CONSTRAINT ck_claim_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),

    CONSTRAINT ck_claim_review_fields
        CHECK (
            (status = 'PENDING' AND reviewed_by_id IS NULL AND reviewed_at IS NULL)
            OR
            (status IN ('APPROVED', 'REJECTED') AND reviewed_by_id IS NOT NULL AND reviewed_at IS NOT NULL)
        )
);

CREATE INDEX idx_claim_policy_id ON insurance_claim(policy_id);
CREATE INDEX idx_claim_submitted_by_id ON insurance_claim(submitted_by_id);
CREATE INDEX idx_claim_status ON insurance_claim(status);
CREATE INDEX idx_claim_submitted_at ON insurance_claim(submitted_at);
